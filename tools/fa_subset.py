#!/usr/bin/env python3
"""Build a self-hosted Font Awesome 7 subset for index.html.

usage: python fa_subset.py <fontawesome-free dir> <repo root>
writes <repo>/assets/vendor/fontawesome/{fa-x.css, fa-solid-x.woff2, fa-brands-x.woff2, LICENSE.txt}
Scans index.html + projects.json for fa-* names so the subset always matches usage.
"""
import os, re, sys
from fontTools import subset

FA, REPO = sys.argv[1], sys.argv[2]
OUT = os.path.join(REPO, 'assets/vendor/fontawesome')
os.makedirs(OUT, exist_ok=True)

used = set()
for f in ('index.html', 'projects.json'):
    used |= set(re.findall(r'fa-[a-z0-9-]+', open(os.path.join(REPO, f), encoding='utf-8').read()))
# style / helper classes, not icons
used -= {'fa-solid', 'fa-regular', 'fa-brands', 'fa-classic', 'fa-fw', 'fa-spin'}
used |= {'fa-sun', 'fa-moon', 'fa-xmark', 'fa-arrow-down', 'fa-arrow-right', 'fa-plus', 'fa-minus', 'fa-play', 'fa-star',
         'fa-file-pdf', 'fa-github', 'fa-linkedin-in', 'fa-x-twitter', 'fa-envelope'}  # x-* UI extras (always kept)

def icon_rules(css_text):
    """yield (selector_names, codepoint) for every icon rule .fa-a,.fa-b{--fa:"\\f005"}"""
    for m in re.finditer(r'([^{}]+)\{--fa:"(\\[0-9a-f]{2,6}|\\[^0-9a-f]|[^"\\])"\}', css_text):
        names = [s.strip()[1:] for s in m.group(1).split(',')]
        yield names, m.group(2)

core = open(os.path.join(FA, 'css/fontawesome.min.css'), encoding='utf-8').read()
solid = open(os.path.join(FA, 'css/solid.min.css'), encoding='utf-8').read()
brands = open(os.path.join(FA, 'css/brands.min.css'), encoding='utf-8').read()

def pick(css_text):
    rules, cps = [], set()
    for names, cp in icon_rules(css_text):
        hit = [n for n in names if n in used]
        if hit:
            rules.append(','.join('.' + n for n in hit) + '{--fa:"' + cp + '"}')
            hexcode = cp.startswith('\\') and len(cp) > 2
            cps.add(int(cp[1:], 16) if hexcode else ord(cp[-1]))
    return rules, cps

solid_rules, solid_cps = pick(core)
brand_rules, brand_cps = pick(brands)
missing = used - {n for r in solid_rules + brand_rules for n in re.findall(r'\.(fa-[a-z0-9-]+)', r)}
if missing:
    print('WARNING not found in FA7:', sorted(missing))

# core = everything in fontawesome.min.css that is not an icon rule (base classes, sizing, animations)
core_base = re.sub(r'[^{}]+\{--fa:"(\\[0-9a-f]{2,6}|\\[^0-9a-f]|[^"\\])"\}', '', core)
core_base = re.sub(r'/\*![\s\S]*?\*/', '', core_base)

def subset_font(src, dst, cps):
    opts = subset.Options(); opts.flavor = 'woff2'; opts.layout_features = ['*']; opts.notdef_outline = True
    font = subset.load_font(src, opts); s = subset.Subsetter(opts); s.populate(unicodes=cps); s.subset(font)
    subset.save_font(font, dst, opts)

subset_font(os.path.join(FA, 'webfonts/fa-solid-900.woff2'), os.path.join(OUT, 'fa-solid-x.woff2'), solid_cps)
subset_font(os.path.join(FA, 'webfonts/fa-brands-400.woff2'), os.path.join(OUT, 'fa-brands-x.woff2'), brand_cps)

head = '/*! Font Awesome Free 7.3.1 subset — https://fontawesome.com/license/free (Icons CC BY 4.0, Fonts SIL OFL 1.1, Code MIT). Generated by fa_subset.py, do not edit. */\n'
faces = (
    ':root{--fa-family-classic:"Font Awesome 7 Free";--fa-family-brands:"Font Awesome 7 Brands"}'
    '@font-face{font-family:"Font Awesome 7 Free";font-style:normal;font-weight:900;font-display:block;src:url(fa-solid-x.woff2) format("woff2")}'
    '@font-face{font-family:"Font Awesome 7 Brands";font-style:normal;font-weight:400;font-display:block;src:url(fa-brands-x.woff2) format("woff2")}'
    '.fas,.fa-solid{--fa-style:900;--fa-family:var(--fa-family-classic)}'
    '.fab,.fa-brands{--fa-style:400;--fa-family:var(--fa-family-brands)}'
)
open(os.path.join(OUT, 'fa-x.css'), 'w', encoding='utf-8').write(head + core_base.strip() + faces + ''.join(solid_rules) + ''.join(brand_rules) + '\n')
open(os.path.join(OUT, 'LICENSE.txt'), 'w').write(open(os.path.join(FA, 'LICENSE.txt')).read())
for f in sorted(os.listdir(OUT)):
    print(f, os.path.getsize(os.path.join(OUT, f)))
print('icons:', len(solid_rules), 'solid rules,', len(brand_rules), 'brand rules')
